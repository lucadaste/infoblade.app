/**
 * Prior parameters for the Beta-Binomial shrinkage in lib/source-quality.js —
 * kept in its own file because scripts/calibrate-source-priors.js regenerates
 * it from real platform data (with --write) rather than these being tuned by
 * hand forever.
 *
 * For each grade tier: `mean` is the assumed baseline accuracy for a source
 * in that tier before we've seen any of ITS OWN track record, and `strength`
 * is how many "pseudo-observations" that assumption is worth — i.e. how much
 * real evidence it takes to move a source's estimate away from the tier
 * average. Both are the alpha/beta of a Beta distribution in disguise:
 *   alpha = mean * strength
 *   beta  = (1 - mean) * strength
 * See betaShrunkAccuracy() in lib/source-quality.js for how these combine
 * with a source's actual attempts/correct counts.
 *
 * These starting values are reasonable priors, NOT yet derived from platform
 * data (see _meta.calibratedAt below) — there isn't enough resolved-prediction
 * volume yet to fit them empirically with confidence. Re-run
 * `node scripts/calibrate-source-priors.js --write` periodically as more
 * predictions resolve to replace these with real numbers.
 */
export const TIER_PRIORS = {
  High:    { mean: 0.65, strength: 20 },
  Medium:  { mean: 0.55, strength: 20 },
  Low:     { mean: 0.45, strength: 20 },
  // Unknown gets a higher strength than the named tiers on purpose: a named
  // tier already carries some editorial signal (we picked "High" for Reuters
  // for a reason), so it's reasonable to let real evidence move it faster.
  // "Unknown" carries no signal at all, so it should take more evidence, not
  // less, before concluding anything — otherwise a single lucky early call
  // would swing an unproven source into "Medium" territory too easily.
  Unknown: { mean: 0.50, strength: 30 },
};

// Regenerated by scripts/calibrate-source-priors.js --write. null means these
// are still the hand-picked defaults above, never replaced with real data.
export const _meta = {
  calibratedAt: null,
  sampleSizes: null,
};
